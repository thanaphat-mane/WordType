package ui;

import java.awt.*;
import javax.swing.*;

/**
 * คลาส UiUtil เป็น "กล่องเครื่องมือช่าง" (Utility Class) สำหรับส่วน UI
 * <p>
 * เหตุผลที่ต้องมีคลาสนี้: เพื่อเก็บค่าคงที่ (Constants) และฟังก์ชันช่วยเหลือ (Helper methods) 
 * ที่ต้องใช้ซ้ำๆ ในหลายๆ หน้าจอ (เช่น สีพื้นหลัง, การโหลดรูปภาพ) 
 * ช่วยลดการเขียนโค้ดซ้ำ และถ้าต้องการเปลี่ยนสีพื้นหลัง ก็มาแก้ที่นี่จุดเดียว โปรแกรมจะเปลี่ยนให้ทั้งหมด
 */
public class UiUtil {
    
    /** 
     * ค่าคงที่สำหรับบอกตำแหน่งโฟลเดอร์เก็บรูปภาพ
     * สาเหตุที่ใช้ "/images/" เพราะเราอ้างอิงจากโฟลเดอร์ resources ในรูปแบบ classpath
     */
    public static final String IMG_PATH = "/images/";

    /**
     * กำหนดสีประจำแอปพลิเคชัน: สีพื้นหลัง (เทาอ่อน)
     * ใช้ Color(234, 234, 234) เพื่อความสบายตา ไม่สว่างหรือมืดเกินไป
     */
    public static final Color BG_COLOR = new Color(234, 234, 234); 
    
    /**
     * กำหนดสีประจำแอปพลิเคชัน: สีแบรนด์/โลโก้ (สีเขียวแกมน้ำเงิน - Teal)
     * ใช้ Color(0, 103, 91) เพื่อเน้นจุดสำคัญ เช่น โลโก้, ค่าความเร็ว WPM, หรือปุ่ม
     */
    public static final Color TEAL = new Color(0, 103, 91);       

    /**
     * ฟังก์ชันสำหรับโหลดรูปภาพมาแสดงผลอย่างปลอดภัย (Safe Loading)
     * <p>
     * เหตุผลที่ต้องเขียนเอง: ถ้าใช้ new ImageIcon("...") แบบธรรมดาแล้วหาไฟล์ไม่เจอ 
     * โปรแกรมอาจจะแครชหรือเกิด NullPointerException ได้ ฟังก์ชันนี้จะจัดการข้อผิดพลาดให้
     * 
     * @param fileName ชื่อไฟล์รูปภาพที่ต้องการโหลด (เช่น "icon.png")
     * @return อ็อบเจ็กต์ ImageIcon ของภาพที่พร้อมนำไปใช้ หรือ null หากไม่พบไฟล์ (ไม่ทำให้แครช)
     */
    public static ImageIcon loadIcon(String fileName) {
        // 1. ใช้ UiUtil.class.getResource() ในการค้นหาไฟล์ตามเส้นทาง (Path) จาก Classpath ของโปรเจกต์
        // ข้อดีคือรองรับการรันจากภายในไฟล์ .jar ด้วย ไม่ใช่แค่อ่านจากโฟลเดอร์ธรรมดา
        java.net.URL url = UiUtil.class.getResource(IMG_PATH + fileName);
        
        // 2. ตรวจสอบว่าระบบเจอไฟล์รูปภาพหรือไม่
        if (url == null) {
            // ถ้าหาไม่เจอ จะไม่โยน Exception แต่จะพิมพ์ข้อความเตือนบอกเส้นทางที่ผิดพลาดลง Console 
            // ให้นักพัฒนาเห็น และรันโปรแกรมต่อไปได้โดยไม่มีรูปภาพนั้น
            System.err.println("ไม่พบไฟล์รูปภาพที่: " + IMG_PATH + fileName);
            return null;
        }
        
        // 3. หากพบไฟล์ ให้นำ URL ที่ได้มาแปลงเป็น ImageIcon เพื่อส่งกลับไปให้ปุ่มหรือป้ายกำกับ (Label) ใช้งาน
        return new ImageIcon(url);
    }
}
