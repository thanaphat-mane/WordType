package model;

/**
 * คลาสโมเดลสำหรับผู้ใช้ (User)
 * <p>
 * เก็บข้อมูลที่เกี่ยวข้องกับผู้ใช้ เช่น ชื่อผู้ใช้ (username) และรหัสผ่านที่ถูก hash แล้ว (hashedPassword)
 * ทำหน้าที่เสมือนกล่องเก็บข้อมูลพื้นฐานที่ใช้ระบุตัวตนของผู้ใช้แต่ละคนภายในระบบ
 */
public class User {
    // -------------------------------------------------------------------------
    // Abstraction Function (AF):
    //   คลาสนี้ทำหน้าที่เป็นตัวแทน (Representation) ของผู้ใช้งานที่ลงทะเบียนในระบบ
    //   - username: คือชื่อผู้ใช้งานที่เป็นตัวระบุตัวตนและไม่ซ้ำกัน เพื่อใช้สำหรับการอ้างอิง
    //   - hashedPassword: คือรหัสผ่านที่ผ่านการเข้ารหัสมาแล้ว (เพื่อความปลอดภัย ไม่เก็บรหัสผ่านจริงที่เป็น plain text)
    //
    // Rep Invariant (RI):
    //   เป็นกฎเกณฑ์ที่รับประกันว่าค่าในฟิลด์จะต้องอยู่ในสภาวะที่ถูกต้องเสมอ
    //   - username: ต้องไม่เป็น null (มีข้อมูลอยู่จริงในหน่วยความจำ) และต้องไม่เป็นแค่ข้อความว่างเปล่า ("")
    //   - hashedPassword: ต้องไม่เป็น null และต้องไม่เป็นแค่ข้อความว่างเปล่า
    // -------------------------------------------------------------------------

    // ประกาศตัวแปรระดับคลาส (instance variables) เพื่อใช้เก็บสถานะ (state) ของออบเจกต์
    // กำหนด access modifier เป็น private เพื่อซ่อนข้อมูลไม่ให้คลาสภายนอกเข้ามาแก้ไขได้โดยพลการ (หลักการ Encapsulation)
    private String username;
    private String hashedPassword;

    /**
     * เมธอดสำหรับตรวจสอบเงื่อนไขที่ห้ามละเมิดเด็ดขาด (Rep Invariant Check)
     * ควรเรียกใช้ทุกครั้งที่มีการสร้าง หรือ เปลี่ยนแปลงข้อมูลภายในคลาส 
     * เพื่อให้ระบบแน่ใจว่าออบเจกต์อยู่ในสถานะที่ถูกต้องเสมอและไม่ทำให้ระบบล่มในภายหลัง
     */
    private void checkRep() {
        // คำสั่ง assert จะทำการเช็คเงื่อนไข (condition) ด้านซ้ายของเครื่องหมายโคลอน (:)
        // หากเงื่อนไขเป็นเท็จ (false) มันจะโยนข้อผิดพลาด AssertionError ออกมาพร้อมกับข้อความด้านขวา
        // - username != null : ตรวจสอบว่าอ้างอิงไปถึงพื้นที่ในหน่วยความจำจริงๆ (ไม่ชี้ไปที่ความว่างเปล่า)
        // - !username.trim().isEmpty() :
        //   .trim() คือคำสั่งของคลาส String ที่ใช้ตัดช่องว่าง (whitespace) ทั้งด้านหน้าและด้านหลังข้อความทิ้งไป
        //   .isEmpty() คือคำสั่งของคลาส String ที่เช็คว่าความยาวของข้อความเท่ากับ 0 หรือไม่ (ทำงานเทียบเท่ากับ .length() == 0)
        //   นำมาใช้ร่วมกันเพื่อกันไม่ให้ผู้ใช้พิมพ์แค่สเปซบาร์รัวๆ ส่งเข้ามาเป็นชื่อผู้ใช้
        assert username != null && !username.trim().isEmpty() : "username must not be null or empty";
        
        // ทำการตรวจสอบในรูปแบบเดียวกันเป๊ะสำหรับรหัสผ่าน
        assert hashedPassword != null && !hashedPassword.trim().isEmpty() : "hashedPassword must not be null or empty";
    }

    /**
     * Constructor (คอนสตรักเตอร์) ของคลาส User
     * ใช้สำหรับกำหนดค่าเริ่มต้นให้แก่ออบเจกต์เมื่อถูกสร้างขึ้นด้วยคำสั่ง 'new' ในคลาสอื่น
     *
     * @param username        ชื่อผู้ใช้ที่ต้องการกำหนด
     * @param hashedPassword  รหัสผ่านที่ผ่านกระบวนการ hash (เข้ารหัสแบบทางเดียว) มาแล้ว
     */
    public User(String username, String hashedPassword){
        // ใช้คีย์เวิร์ด 'this' เพื่ออ้างถึงตัวแปร private ของคลาสนี้ (this.username)
        // และนำค่าจากตัวแปร parameter (username) ฝั่งขวามาใส่ลงไป
        this.username = username;
        
        // ทำแบบเดียวกันกับ hashedPassword เพื่อเก็บสถานะไว้ในออบเจกต์
        this.hashedPassword = hashedPassword;
        
        // หลังจากกำหนดค่าเรียบร้อยแล้ว จำเป็นต้องเรียก checkRep() ทันที
        // เพื่อป้องกันกรณีที่คลาสอื่นส่งค่า null หรือช่องว่างมาสร้างออบเจกต์ ซึ่งจะทำให้ข้อมูลผิดพลาดแต่แรก
        checkRep();
    }

    /**
     * ดึงค่าชื่อผู้ใช้ (Getter method)
     * เนื่องจากตัวแปร username ถูกกำหนดเป็น private หากคลาสอื่นต้องการรู้ชื่อผู้ใช้ จะต้องเรียกผ่านเมธอดนี้
     *
     * @return ชื่อผู้ใช้ (String) ของ user ออบเจกต์นี้
     */
    public String getUsername(){
        // เพียงแค่คืนค่าตัวแปร username ออกไป โดยที่ผู้เรียกไม่สามารถเปลี่ยนแปลงต้นฉบับได้
        return username;
    }

    /**
     * ดึงค่ารหัสผ่านที่ถูก hash แล้ว (Getter method)
     *
     * @return รหัสผ่านที่ถูก hash แล้วเป็นสตริง (ไม่ใช่รหัสผ่านจริงที่ผู้ใช้มองเห็น)
     */
    public String getHashedPassword(){
        // คืนค่า hashedPassword ออกไป มักใช้เพื่อเปรียบเทียบในขั้นตอนการล็อกอิน
        return hashedPassword;
    }
}
