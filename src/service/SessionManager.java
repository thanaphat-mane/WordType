package service;
import model.User;

/**
 * อินเตอร์เฟซ (Interface) สำหรับจัดการเซสชันของผู้ใช้งานในระบบ
 * 
 * ในภาษา Java, Interface ทำหน้าที่เปรียบเสมือน "สัญญา" (Contract) ที่กำหนดว่า
 * คลาสใดๆ ที่นำ Interface นี้ไปใช้ (Implement) จะต้องมีพฤติกรรม (Method) อะไรบ้าง
 * โดยไม่ได้บอกว่าจะทำงานนั้นๆ อย่างไร (ซ่อน Implementation Details)
 * 
 * การใช้ SessionManager จะช่วยให้เราสามารถเปลี่ยนวิธีการเก็บเซสชันในอนาคตได้ง่ายๆ
 * เช่น จากเดิมเก็บในหน่วยความจำ (InMemorySession) อาจจะเปลี่ยนไปเก็บในฐานข้อมูลหรือไฟล์ 
 * โดยที่คลาสอื่นๆ ที่เรียกใช้งานไม่ต้องแก้ไขโค้ดใดๆ เลย (ยึดหลัก Polymorphism)
 */
public interface SessionManager {

    /**
     * เมธอดสำหรับบันทึกข้อมูลผู้ใช้งานเข้าสู่ระบบ
     * คลาสที่ Implement เมธอดนี้ต้องหาวิธีจดจำว่าผู้ใช้นี้กำลังออนไลน์อยู่
     * 
     * @param user อ็อบเจกต์ของผู้ใช้งานที่เพิ่งผ่านการตรวจสอบและล็อกอินสำเร็จ
     */
    void login(User user);

    /**
     * เมธอดสำหรับนำผู้ใช้งานออกจากระบบ (ล็อกเอาต์)
     * คลาสที่ Implement เมธอดนี้ต้องเคลียร์ข้อมูลหรือลบสถานะการล็อกอินของผู้ใช้ปัจจุบัน
     */
    void logout();

    /**
     * เมธอดสำหรับดึงข้อมูลผู้ใช้งานที่กำลังล็อกอินอยู่ในขณะนั้น
     * 
     * @return อ็อบเจกต์ User ของผู้ใช้งานปัจจุบัน หรือคืนค่า null หากยังไม่ได้ล็อกอิน
     */
    User getCurrentUser();

    /**
     * เมธอดสำหรับตรวจสอบสถานะว่าระบบตอนนี้มีคนใช้งานอยู่หรือไม่
     * 
     * @return คืนค่า true หากมีผู้ใช้งานล็อกอินอยู่ (มี Session อยู่), คืนค่า false หากไม่มี
     */
    boolean isLoggedIn();
}
