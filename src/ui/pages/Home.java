package ui.pages;

import java.awt.*;
import javax.swing.*;

import ui.UiUtil;
import ui.components.HeaderBar;
import ui.components.ModeSelector;
import ui.components.TypingView;

/**
 * คลาส Home ทำหน้าที่เป็นหน้าจอหลัก (Main Screen) ของโปรแกรมพิมพ์ดีด (WordType)
 * <p>
 * เมื่อผู้ใช้ล็อกอินสำเร็จ หรือเปิดแอปพลิเคชันขึ้นมา จะเจอกับหน้านี้
 * โดยหน้านี้ทำหน้าที่เป็น "ที่ประกอบร่าง" ของคอมโพเนนต์ย่อยๆ หลายตัวมารวมกัน (Composition) 
 * เช่น แถบเมนูด้านบน, ตัวเลือกโหมดการพิมพ์, ลานประลองพิมพ์ดีด, และปุ่มเริ่มใหม่
 */
public class Home extends JPanel {

    /**
     * คอนสตรักเตอร์ (Constructor) สำหรับหน้าจอ Home
     * หน้าที่: เตรียมพื้นที่ กำหนดสี และนำส่วนประกอบ (Components) ต่างๆ มาวางตามพิกัด
     */
    public Home() {
        // 1. ปิดระบบจัดการเลย์เอาต์อัตโนมัติ (Absolute Positioning)
        // เหตุผล: เพื่อให้เราสามารถระบุตำแหน่ง X, Y และความกว้าง/สูง (setBounds) ของคอมโพเนนต์
        // ได้อย่างอิสระตามดีไซน์เป๊ะๆ (Figma) โดยไม่ถูกบังคับโดย Java Layout Manager
        setLayout(null);
        
        // 2. กำหนดสีพื้นหลังให้กับหน้าจอนี้ โดยดึงสีมาตรฐาน (เทาอ่อน) จากคลาส UiUtil
        setBackground(UiUtil.BG_COLOR);

        // ----------------------------------------------------
        // 3. ส่วนหัวของหน้าจอ (Header Bar)
        // ----------------------------------------------------
        // สร้างอ็อบเจ็กต์ HeaderBar (ซึ่งมีการจัดเรียงโลโก้, เมนูต่างๆ ไว้ในตัวมันเองแล้ว)
        // แล้วนำมาแปะลงในหน้านี้ (ไม่ต้องตั้งพิกัด เพราะ HeaderBar อาจจะจัดการตัวเองแล้ว)
        HeaderBar header = new HeaderBar();
        add(header);

        // ----------------------------------------------------
        // 4. ส่วนเลือกโหมดการทดสอบ (Mode Selector)
        // ----------------------------------------------------
        // สร้างตัวเลือกโหมดการพิมพ์ (เช่น พิมพ์ตามเวลา, พิมพ์ตามจำนวนคำ)
        ModeSelector modeSelector = new ModeSelector(); 
        // กำหนดตำแหน่งให้อยู่ตรงกลางหน้าจอด้านบน (X=342, Y=125) และมีขนาดกว้าง 486 สูง 38 พิกเซล
        modeSelector.setBounds(342, 125, 486, 38); 
        add(modeSelector);

        // ----------------------------------------------------
        // 5. พื้นที่พิมพ์ข้อความ (Typing View)
        // ----------------------------------------------------
        // หัวใจหลักของหน้านี้คือ TypingView ที่เป็นกล่องแสดงข้อความให้ผู้ใช้พิมพ์ตาม
        TypingView typingView = new TypingView();
        // จัดให้อยู่ตรงกลางหน้าจอค่อนไปทางข้างล่าง (X=150, Y=280) ขนาดกว้าง 900 เพื่อรองรับข้อความยาวๆ
        typingView.setBounds(150, 280, 900, 160); 
        add(typingView);

        // ----------------------------------------------------
        // 6. ปุ่มเริ่มใหม่ (Restart Button)
        // ----------------------------------------------------
        // สร้างป้ายกำกับ (JLabel) มาทำหน้าที่เป็นปุ่มแทน JButton แบบปกติ เพื่อความสวยงาม
        JLabel btnRestart = new JLabel();
        // โหลดรูปภาพไอคอนรีสตาร์ทมาใส่ (ถ้าหาไม่เจอ จะไม่โชว์ แต่โปรแกรมไม่แครชเพราะ UiUtil จัดการไว้)
        btnRestart.setIcon(UiUtil.loadIcon("btnRestart.png"));
        // วางพิกัดให้อยู่ตรงกลางจอใต้พื้นที่พิมพ์ (X=588, Y=465)
        btnRestart.setBounds(588, 465, 24, 24);
        // เปลี่ยนเคอร์เซอร์เมาส์ให้เป็น "รูปมือคลิก" เมื่อนำเมาส์ไปชี้เหนือปุ่ม
        btnRestart.setCursor(new Cursor(Cursor.HAND_CURSOR));
        add(btnRestart);

        // ----------------------------------------------------
        // 7. คำอธิบายคีย์ลัด (Shortcut Label)
        // ----------------------------------------------------
        // สร้างข้อความอธิบายให้ผู้ใช้รู้ว่า ถ้ากดปุ่ม ESC บนคีย์บอร์ด จะเป็นการรีสตาร์ทการทดสอบ
        // สังเกตว่ามีการใช้แท็ก HTML <html>...</html> ภายในข้อความ
        // เหตุผล: เพื่อให้สามารถทำตัวหนังสือสองสีใน Label เดียวกันได้ 
        // (คำว่า [ESC] เป็นสีเขียว Teal, ส่วนคำอธิบายเป็นสีดำ)
        JLabel lblShortcut = new JLabel("<html><font color='#006664'>[ ESC ]</font> <font color='#000000'>- restart test</font></html>");
        
        // กำหนดฟอนต์ให้เป็นสไตล์โค้ดดิ้ง (Menlo แบบหนา) เพื่อให้ดูเข้ากับปุ่มบนคีย์บอร์ด
        lblShortcut.setFont(new Font("Menlo", Font.BOLD, 14));
            
        // กำหนดตำแหน่ง X ให้อยู่ใต้ปุ่มไอคอนรีสตาร์ทพอดี (X=508, Y=610)
        lblShortcut.setBounds(508, 610, 184, 18);
        
        // สั่งให้ข้อความภายในกล่องถูกจัดตำแหน่งให้อยู่ "กึ่งกลาง" (Center Alignment)
        lblShortcut.setHorizontalAlignment(SwingConstants.CENTER); 
        add(lblShortcut);
    }
}
