package repository;
import java.util.*; // นำเข้าไลบรารีพื้นฐานของ Java รวมถึง List, ArrayList เป็นต้น

import model.User; // นำเข้าคลาส User ของโปรเจกต์มาเพื่อใช้สร้างและดึงข้อมูลออบเจกต์
import util.CSVUtil; // นำเข้าเครื่องมือที่เขียนขึ้นเองสำหรับช่วยอ่านและเขียนไฟล์ CSV

/**
 * คลาสสำหรับจัดการข้อมูลผู้ใช้ในฐานข้อมูล (ในโปรเจกต์นี้เก็บเป็นไฟล์ CSV)
 * <p>
 * ทำหน้าที่ตามหลักการออกแบบ Repository Pattern คือทำตัวเป็นเสมือนที่เก็บข้อมูลรวม (Collection) 
 * ซ่อนรายละเอียดอันวุ่นวายของการอ่านเขียนไฟล์ (File I/O) ทำให้ส่วนอื่นของแอปพลิเคชันไม่ต้องไปยุ่งเกี่ยวกับไฟล์ตรงๆ
 */
public class UserRepository {

    // กำหนดค่าคงที่เป็น String เก็บพาร์ท (path) ของไฟล์ CSV ที่จะไปใช้อ่านเขียน
    // ใช้ static final เพื่อให้ประหยัดพื้นที่หน่วยความจำและไม่สามารถถูกแก้ไขระหว่างรันโปรแกรมได้
    private static final String FILE_PATH = "./src/data/users.csv";

    /**
     * ตรวจสอบว่ามีผู้ใช้ที่มีชื่อผู้ใช้นี้ในระบบ (ในไฟล์ CSV) อยู่หรือยัง
     *
     * @param username ชื่อผู้ใช้ที่ต้องการตรวจสอบว่ามีซ้ำหรือไม่
     * @return true ถ้ามีชื่อผู้ใช้นี้อยู่แล้ว (ห้ามใช้ซ้ำ), false ถ้ายังไม่มี (สามารถลงทะเบียนได้)
     */
    public boolean existsByUsername(String username){
        // ตรรกะคือ: ลองพยายามค้นหาผู้ใช้นี้ด้วยเมธอด FindByUsername()
        // ถ้าเมธอดนั้นคืนค่าที่ไม่ใช่ null (หมายถึงหาเจอและได้ออบเจกต์กลับมา) ก็จะได้ผลลัพธ์เป็น true
        // แต่ถ้าคืนค่ามาเป็น null (ไม่เจอ) ก็จะได้เป็น false
        return FindByUsername(username) != null;
    }
    
    /**
     * ทำการค้นหาผู้ใช้จากชื่อผู้ใช้
     *
     * @param username ชื่อผู้ใช้ที่เป็นเป้าหมายในการค้นหา
     * @return คืนค่าออบเจกต์ User ที่มีข้อมูลครบถ้วนหากพบข้อมูล, แต่ถ้าหาไม่เจอในไฟล์เลย จะคืนค่า null กลับไป
     */
    public User FindByUsername(String username){
        // เรียกใช้ฟังก์ชัน readAll จากคลาส CSVUtil ซึ่งน่าจะทำหน้าที่อ่านไฟล์ตามเส้นทาง (FILE_PATH) ทีละบรรทัด 
        // แล้วนำมาแยก (split) ด้วยลูกน้ำ (',') เก็บไว้ในอาเรย์ String (String[])
        // ผลลัพธ์สุดท้ายที่คืนกลับมาคือ List (คล้ายๆ อาเรย์ที่ยืดหดได้) ที่รวบรวมทุกบรรทัดไว้
        List<String[]> rows = CSVUtil.readAll(FILE_PATH);
        
        // เราใช้ Enhanced for-loop (หรือ For-each) 
        // อธิบาย: ดึงข้อมูลออกมาทีละแถว (String[]) จากในลิสต์ (rows) มาพักไว้ในตัวแปรชื่อ row
        // แล้วประมวลผลตรรกะในวงเล็บปีกกา เมื่อจบแถวนี้ ก็จะวนกลับไปดึงแถวถัดไปมาอัตโนมัติจนกว่าจะครบทุกตัว
        for (String[] row : rows) {
            // ตรวจสอบความปลอดภัย 2 อย่างด้วยเครื่องหมาย && (AND):
            // 1. row.length >= 2 : เช็คว่าบรรทัดนี้หลังจากแตกด้วยลูกน้ำแล้ว มีคอลัมน์อย่างน้อย 2 ช่องหรือไม่ (เพื่อกัน Array Index Out of Bounds หากไฟล์เสีย)
            // 2. row[0].equals(username) : ตรวจสอบว่าข้อมูลในคอลัมน์แรก (index 0 ซึ่งก็คือ username ในไฟล์) ตรงกับชื่อผู้ใช้ที่กำลังค้นหาอยู่หรือไม่
            if(row.length >= 2 && row[0].equals(username)){
                // หากเจอเงื่อนไขตรงกันทั้งคู่ แปลว่าค้นพบผู้ใช้งานนั้นในไฟล์แล้ว
                // ทำการสร้างออบเจกต์ User ขึ้นมาใหม่ (new User(...)) 
                // โดยดึงเอาชื่อ (row[0]) และรหัสผ่านที่ hash แล้ว (row[1]) ส่งให้คอนสตรักเตอร์
                // และทำการ 'return' คืนค่าทันที ซึ่งจะทำให้กระบวนการลูปยุติลงทันทีแบบไม่ต้องเสียเวลาวนจนจบไฟล์
                return new User(row[0], row[1]);
            }
        }
        // หากลูป for ทำงานจนจบครบทุกบรรทัดแล้วยังไม่เคยเจอเงื่อนไขเป็น true เลย (ก็คือไม่เคย return ออกไปก่อน)
        // แสดงว่าผู้ใช้นี้ไม่มีอยู่ในระบบ จึงทำการคืนค่า null เพื่อบอกผู้เรียกใช้ว่า "หาไม่พบนะ"
        return null;
    }

    /**
     * บันทึกข้อมูลของผู้ใช้งานหน้าใหม่ลงในไฟล์
     *
     * @param user ออบเจกต์ User ที่มีข้อมูลครบ (ทั้งชื่อและรหัสผ่าน) ที่ต้องการบันทึกลงไป
     */
    public void save(User user){
        // ทำการเรียกฟังก์ชัน appendRow (คือการต่อท้ายไฟล์โดยไม่ลบข้อมูลเก่า) ของคลาส CSVUtil
        // ส่งตำแหน่งของไฟล์ (FILE_PATH) ไปพร้อมกับอาเรย์ขนาด 2 ช่อง ที่เพิ่งสร้างใหม่ทันทีแบบย่อ (new String[]{...})
        // โดยช่องแรกคือ user.getUsername() และช่องสองคือ user.getHashedPassword() 
        // ซึ่งเบื้องหลังคลาส CSVUtil ก็จะนำเอา 2 ช่องนี้มาต่อกันคั่นด้วยเครื่องหมายลูกน้ำ และขึ้นบรรทัดใหม่ไปเขียนใส่ไฟล์
        CSVUtil.appendRow(FILE_PATH, new String[]{user.getUsername(), user.getHashedPassword()});
    }
}
